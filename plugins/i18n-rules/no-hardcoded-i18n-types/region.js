/**
 * Checks if a given country name or ISO code is hardcoded in the lists.
 * @param {string} _value - The country name or ISO code to check.
 * @param {Object} node - The node object from which the value is derived, used for determining the type of check to perform.
 * @returns {string|false} - Returns a warning message if a hardcoded value is found, otherwise returns false.
 */
function isRegionNameOrCodeHardCoded(_value, node) {
  const value = _value.toLowerCase();
  let errorMessage = '';

  /*
    We are intentionally checking the Literal only and ignoring the JSXText, TemplateLiteral as this may overwhelms the developer on the cases like using the "in", "at" in any large string. With the Literal check it self, we can find the maximum issues related to country codes.

    Search algos are not required to optimize search, since this is a single of check.
  */
  if (node.type === 'Literal' && regionISOs.some((iso) => value === iso)) {
    errorMessage = `Avoid using hardcoded "region code" in your code, this feature may not be available for all countries. If you think this error is wrong, ignore the it.`;
  } else if (regionNamesList.some((regionName) => value.includes(regionName))) {
    errorMessage = `Avoid using hardcoded "region names" in your code, this feature may not be available for all regions. If required wrap this feature under the feature flag.`;
  }

  return errorMessage.length > 0 ? errorMessage : false;
}

module.exports = isRegionNameOrCodeHardCoded;
