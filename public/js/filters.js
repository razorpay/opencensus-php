'use strict';
/* Filters */
// need load the moment.js to use this filter.
angular
  .module('app.filters', [])
  .filter('fromNow', function() {
    return function(date) {
      return moment(date).fromNow();
    };
  })
  .filter('titlecase', function() {
    return function(input) {
      if (!input) return input;
      var words = input.toString().split(/[\s_]/);
      for (var i = 0; i < words.length; i++) {
        words[i] = words[i].charAt(0).toUpperCase() + words[i].slice(1);
      }
      return words.join(' ');
    };
  })
  .filter('rupee', function() {
    return function(input, symbol) {
      if (!input) {
        input = 0;
      }
      // If passing an alternate symbol like INR suffix it with a space
      if (typeof symbol === 'undefined') {
        // This is Rupee symbol unicode code point
        // https://codepoints.net/U+20B9
        symbol = '\u20b9';
      }

      // Poke @pranav about the regex
      var splits = input
        .toFixed(2)
        .toString()
        .match(/-?([^-]{1,3}(\..+)?$|[^-]{1,2}(?=.([^\.]{2})+(\..+)?$))/g);
      return symbol + splits.join(',');
    };
  })
  .filter('capitalize', function() {
    return function(input) {
      return !!input
        ? input.charAt(0).toUpperCase() + input.substr(1).toLowerCase()
        : '';
    };
  })
  .filter('propercurrency', [
    '$filter',
    function($filter) {
      return function(input, currency) {
        switch (currency) {
          case 'USD':
            return $filter('currency')(input, '$', 2);
          case 'INR':
            return $filter('rupee')(input);
          // This is if you want two decimal places
          case '':
            return $filter('currency')(input, '', 2);
        }
      };
    },
  ])
  .filter('roletoname', function() {
    return function(role, helptext) {
      var rolesLabels = {
        operations: 'Operations',
        support: 'Support',
        finance: 'Finance',
        admin: 'Admin',
        sellerapp: 'ePOS',
        manager: 'Manager',
        owner: 'Owner',
      };

      var rolesHelpText = {
        operations:
          'Allows access to all views. Cannot make configuration or team changes. Useful for day-to-day operations like handling refunds and settlements.',
        support:
          'Can access payments, refunds, invoices, and orders. Cannot do any write operations like refunds or captures.',
        finance:
          'Can see payments related data, including Reports and Settlements.',
        admin: 'Can do everything except for Team Management.',
        sellerapp:
          "Can only create and read invoices and payment links generated by their own account. Invoices created by other users in your team won't be visible to this role",
        manager:
          'Allows access to all views except for Team Management and Key Generation.',
      };

      if (typeof helptext !== 'undefined') {
        return rolesHelpText[role];
      } else {
        return rolesLabels[role];
      }
    };
  })
  .filter('methodtoname', function() {
    return function(method) {
      var methodNames = {
        card: 'Card',
        netbanking: 'Netbanking',
        upi: 'UPI',
        emi: 'EMI',
        wallet: 'Wallet',
        null: 'All',
        bank_transfer: 'Bank Transfer',
      };

      return methodNames[method];
    };
  });
