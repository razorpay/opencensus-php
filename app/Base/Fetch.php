<?php

namespace RZP\Base;

use App;
use RZP\Constants\Entity;
use RZP\Constants\Fields;
use RZP\Exception\BadRequestValidationFailureException;
use RZP\Exception\LogicException;
use RZP\Http\BasicAuth\Type;
use RZP\Models\Payment\Method;
use RZP\Models\Payment\Processor\Upi;
use RZP\Models\Payment\Processor\Wallet;
use RZP\Models\Payment\Status;
use RZP\Trace\TraceCode;

class Fetch
{
    const LABEL         = 'label';
    const TYPE          = 'type';
    const VALUES        = 'values';

    const STRING   = 'string';
    const NUMBER   = 'number';
    const BOOLEAN  = 'boolean';
    const ARRAY    = 'array';
    const OBJECT   = 'object';

    /**
     * RULES is used to define validation rules for all fields is Entity.
     * RULES is an multi-dimentional array which can have these types.
     * DEFAULT|PRIVATE_AUTH|PROXY_AUTH|PRIVILEDGE_AUTH|ADMIN_AUTH
     *
     * Final rules are accumulated by merging rules according to Auth Type
     */
    const RULES = [];

    /**
     * All the entities must be defined in default set of rules
     */
    const RULE_DEFAULT = 'default';

    /**
     * ACCESSES defines the list the fields can be accessed for auth type
     * ACCESSES is an multi-dimentional array which can have these types.
     * PRIVATE_AUTH|PROXY_AUTH|PRIVILEDGE_AUTH|ADMIN_AUTH
     *
     * Final access list is generated by merging rules according to Auth Type
     */
    const ACCESSES = [];

    /**
     * Fields which are signed and need to be resolved before actual search
     */
    const SIGNED_IDS    = [];

    /**
     * Fields which needs to searched from ES.
     */
    const ES_FIELDS     = [];

    /**
     * Fields which are indexed in ES and also in MySQL.
     */
    const COMMON_FIELDS = [];

    const EXPAND       = 'expand';
    const EXPAND_EACH  = 'expand.*';
    const FROM         = 'from';
    const TO           = 'to';
    const COUNT        = 'count';
    const SKIP         = 'skip';


    private $defaultFetchRules = [
        self::FROM          => 'integer',
        self::TO            => 'integer',
        self::COUNT         => 'integer|min:1',
        self::SKIP          => 'integer',

        //
        // Idea is, by default expand can be send in query for all current
        // fetch routes, similar to other common query parameter eg. skip etc.
        //
        // By default no value is allowed, one must specify the same(2nd line)
        // in respective repository branch. This is done to avoid unnecessary
        // exposing of relation attributes.
        //

        self::EXPAND        => 'sometimes|array|max:5',
        self::EXPAND_EACH   => 'string|in:',
    ];

    /**
     * Until now query parameters were only expected in 'fetch'
     * routes (e.g. GET /invoices) and so we have validation
     * rule sets on it based on authentication type. But now
     * with new use cases (e.g. expands) we would need validations
     * on 'find' routes (eg. GET /invoices/{id}).
     *
     * Also observation is allowed 'find' parameters set is always
     * going to be subset of 'fetch' parameters set. Following is
     * a set of query parameters to be allowed in 'find' routes.
     * We use this to validate the query parameters in those routes.
     *
     * @var array
     */
    protected $findRuleKeys = [
        self::EXPAND,
        self::EXPAND_EACH,
    ];

    /**
     * @var \RZP\Http\BasicAuth\BasicAuth $auth
     */
    private $auth;

    /**
     * Acculmulated list of run generated at run-time in accordance with the Auth
     *
     * @var array
     */
    private $fetchRules;

    /**
     * We can disable any Fetch Read with this property.
     * If disabed, fetchRules will be read from Repository
     * Later: We can also disable complete reads for an Entity
     *
     * @var bool $disabled
     */
    protected $enabled = true;

    public function __construct()
    {
        $this->app = App::getFacadeRoot();

        $this->auth = $this->app['basicauth'];

        $this->trace = $this->app['trace'];
    }

    public function isEnabled() : bool
    {
        return ($this->enabled === true);
    }

    /**
     * Do a bunch of processing on the fetch param rules:
     * - Unset all the empty params (w/o any value)
     * - Add default params (internal [count] and user-defined) to the params list.
     * - Validate all the params against $fetchRules
     *
     * @param  array $params
     */
    public function processFetchParams(array & $params)
    {
        $this->unsetEmptyParams($params);

        $this->addDefaultParams($params);

        // validateFetchParams modifies fetchParamRules.
        // To check for ES fetch, we needs the original set of fetchParamRules (basically the default set)
        //$this->defaultFetchParamRules = $this->fetchParamRules;
        $this->validateFetchParams($params);

        $this->modifyFetchParams($params);
    }

    /**
     * Groups all the incoming params in to the set of MySQL and ES.
     *
     * @param array $params
     * @return array [ [MySQL Fields], [ESFields] ]
     * @throws BadRequestValidationFailureException
     */
    public function groupMysqlAndEsParams(array $params): array
    {
        $esFetchKeys = static::ES_FIELDS;
        $commonFetchKeys = static::COMMON_FIELDS;

        /*
         * If there is no ES Field defined in Fetch class then
         * we direct all the fields to MySQL
         */
        if ((empty($esFetchKeys) === true) and
            (empty($commonFetchKeys) === true))
        {
            return [$params, []];
        }

        /*
         * Following is list of keys common to Es & MySQL, only in ES, only in
         * MySQL respectively.
         * These do not include default keys(e.g. skip, count).
         */
        $mysqlFetchKeys  = array_values(array_diff(
                               array_keys($this->fetchRules),
                               array_keys($this->defaultFetchRules),
                               $esFetchKeys,
                               $commonFetchKeys));

        /*
         * Get input params which are not a part of the:
         * - Default param rules (see $fetchParamRules definition above), plus
         * - Common keys defined in EsRepo.
         *
         * The remainder/filtered list has to be a subset of either MySQL or ES keys
         * exclusively, otherwise an error will be raised. Hence both MySQL and
         * ES cannot be searched together in a single fetch operation.
         */
        $filteredParamsKeys = array_values(array_diff(
                                  array_keys($params),
                                  array_keys($this->defaultFetchRules),
                                  $commonFetchKeys));

        if (empty(array_diff($filteredParamsKeys, $mysqlFetchKeys)) === true)
        {
            // First value is MySQL params, so fetch will happen via MySQL
            return [$params, []];
        }
        else if (empty(array_diff($filteredParamsKeys, $esFetchKeys)) === true)
        {
            // Second value is Es params, so fetch will happen via Es
            return [[], $params];
        }
        else
        {
            $extraKeys = array_values(array_diff($filteredParamsKeys, $esFetchKeys));

            $message = implode(', ', $extraKeys) . ' not expected with other params sent';

            throw new BadRequestValidationFailureException(
                $message,
                null,
                [
                    'params_keys'       => array_keys($params),
                    'common_fetch_keys' => $commonFetchKeys,
                    'es_fetch_keys'     => $esFetchKeys,
                    'mysql_fetch_keys'  => $mysqlFetchKeys,
                    'extra_keys'        => $extraKeys,
                ]);
        }
    }

    public function processFindParams(array &$params)
    {
        $this->modifyFindParams($params);

        $this->validateFindParams($params);
    }

    protected function unsetEmptyParams(array &$params)
    {
        foreach ($params as $key => $value)
        {
            if ($params[$key] === '')
            {
                unset($params[$key]);
            }
        }
    }

    protected function addDefaultParams(array & $params)
    {
        $this->addDefaultParamCountAndUpdateRulesByAuthType($params);
    }

    protected function validateFetchParams(array $params)
    {
        (new JitValidator)->rules($this->getAllFetchRules())
                          ->caller($this)
                          ->input($params)
                          ->validate();

        $this->validateAdditional($params);
    }

    protected function validateAdditional(array &$param)
    {
        // Can be overridden when required
    }

    protected function modifyFetchParams(array & $params)
    {
        $signIds = array_flip(static::SIGNED_IDS);

        if (count($signIds) === 0)
        {
            return;
        }

        $keys = array_keys(array_intersect_key($params, $signIds));

        foreach ($keys as $key)
        {
            $entityKey = $key;

            // Remove '_id' prefix at end.
            if (substr($key, -3) === '_id')
            {
                $entityKey = substr($key, 0, -3);
            }

            // If not valid entity, then continue the loop
            if (Entity::isValidEntity($entityKey) === false)
            {
                continue;
            }

            // Gets entity class
            $entityClass = Entity::getEntityClass($entityKey);

            $value = $params[$key];

            if (($this->auth->isAdminAuth() === true) or
                ($this->auth->isPrivilegeAuth() === true))
            {
                // In case of admin auth, don't throw exception
                // if sign is not there
                $entityClass::verifyIdAndSilentlyStripSign($value);
            }
            else
            {
                $entityClass::verifyIdAndStripSign($value);
            }

            $params[$key] = $value;
        }
    }

    protected function addDefaultParamCountAndUpdateRulesByAuthType(array & $params)
    {
        $max    = 1000;
        $count  = 1000;

        if ($this->auth->isPrivilegeAuth() === false)
        {
            $max    = 100;
            $count  = 10;
        }

        $this->defaultFetchRules['count'] .= '|max:'.$max;

        if (isset($params['count']) === false)
        {
            $params['count'] = $count;
        }
    }

    /**
     * Temporary:
     * There are clients(including Dashboard) which is sending
     * skip,count like extra parameters in GET routes. For now
     * everything which is not expected would be ignored. We'll
     * keep trace of violations and act on it later.
     *
     * @param array $params
     */
    protected function modifyFindParams(array &$params)
    {
        $filtered = array_only($params, $this->findRuleKeys);

        if (count($filtered) !== count($params))
        {
            $this->trace->info(TraceCode::EXTRA_QUERY_PARAM_IN_GET_ROUTE, $params);
        }

        $params = $filtered;
    }

    /**
     * Validates query parameters passed during GET by id endpoints.
     * E.g. GET /invoices/inv_123?expand[]=payments
     *
     * @param array $params
     */
    protected function validateFindParams(array $params)
    {
        $fetchParamRules = $this->getAllFetchRules();

        $findParamRules = array_intersect_key(
                              $fetchParamRules,
                              array_flip($this->findRuleKeys));

        (new JitValidator)->rules($findParamRules)
                          ->caller($this)
                          ->input($params)
                          ->validate();
    }

    /**
     * Validation runs against merged rules.
     *
     * @return array
     */
    public function getAllFetchRules()
    {
        $this->setRulesForAuth();

        $mergedRules = array_merge($this->defaultFetchRules, $this->fetchRules);

        return $mergedRules;
    }

    /**
     * Function will resolve RULES and ACCESSES based on the auth.
     * $rules is merged array of (default,app
     *
     * @return array ['rules' => [], 'accesses' => []]
     */
    private function setRulesForAuth()
    {
        $defaultAccesses = array_keys($this->defaultFetchRules);

        $rules = $this->readRules(self::RULE_DEFAULT);
        $accesses = array_merge($defaultAccesses, $this->readAccesses(Type::PRIVATE_AUTH));

        if ($this->auth->isProxyOrPrivilegeAuth())
        {
            $rules = array_merge($rules, $this->readRules(Type::PROXY_AUTH));
            $accesses = array_merge($accesses, $this->readAccesses(Type::PROXY_AUTH));
        }

        if ($this->auth->isPrivilegeAuth())
        {
            $rules = array_merge($rules, $this->readRules(Type::PRIVILEGE_AUTH));
            $accesses = array_merge($accesses, $this->readAccesses(Type::PRIVILEGE_AUTH));
        }

        if ($this->auth->isAdminAuth())
        {
            $rules = array_merge($rules, $this->readRules(Type::ADMIN_AUTH));
            $accesses = array_merge($accesses, $this->readAccesses(Type::ADMIN_AUTH));
        }

        $this->fetchRules = array_only($rules, $accesses);
    }

    private function readRules($key)
    {
        $rules = array_get(static::RULES, $key, []);

        if (is_array($rules) === false)
        {
            throw new LogicException(sprintf("%s::RULES[%s] must be an array", static::class, $key));
        }

        return $rules;
    }

    private function readAccesses($key)
    {
        $accesses = array_get(static::ACCESSES, $key, []);

        if (is_array($accesses) === false)
        {
            throw new LogicException(sprintf("%s::ACCESSES[%s] must be an array", static::class, $key));
        }

        return $accesses;
    }

    public static function getCommonFields()
    {
        $gatewayList = config('gateway.available');
        $statusList  = Status::getStatusList();
        $methodList  = Method::getMethodsNamesMap();
        $walletList  = Wallet::getWalletNetworkNamesMap();
        $upiList     = Upi::getFullBankNamesMap();

        return [
            // Merchant
            Fields::MERCHANT_ID => [
                self::LABEL     => 'Merchant Id',
                self::TYPE      => self::STRING
            ],
            // Gateway
            Fields::GATEWAY => [
                self::LABEL     => 'Gateway',
                self::TYPE      => self::ARRAY,
                self::VALUES    => $gatewayList
            ],
            //Payment
            Fields::PAYMENT_STATUS => [
                self::LABEL     => 'Status',
                self::TYPE      => self::ARRAY,
                self::VALUES    => $statusList
            ],
            Fields::PAYMENT_ID => [
                self::LABEL     => 'Payment Id',
                self::TYPE      => self::STRING,
            ],
            // Method
            Fields::METHOD => [
                self::LABEL     => 'Method',
                self::TYPE      => self::OBJECT,
                self::VALUES    => $methodList
            ],
            // Wallet
            Fields::WALLET => [
                self::LABEL     => 'Wallet',
                self::TYPE      => self::OBJECT,
                self::VALUES    => $walletList
            ],
            // UPI
            Fields::UPI => [
                self::LABEL     => 'UPI',
                self::TYPE      => self::OBJECT,
                self::VALUES    => $upiList
            ]
        ];
    }

}
