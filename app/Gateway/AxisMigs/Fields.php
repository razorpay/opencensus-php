<?php

namespace RZP\Gateway\AxisMigs;

use RZP\Gateway\Base;

class Fields
{
    /**
     * A single digit response from the Payment Server that is mapped from
     * the AcqCSCRespCode showing the level of match that occurred with
     * the CSC check.
     * For more information, see CSC Level Codes.
     * If the transaction was declined because the CSC check failed,
     * a QSIResponseCode value of "2" - 'Bank
     * Declined Transaction' will be returned.
     * If the acquiring institution does not support CSC,
     * the vpc_CSCResultCode will show 'Unsupported'.
     * Output Alpha 1,11 M
     */
    const VPC_CSCRESULTCODE = 'vpc_CSCResultCode';

    /**
     * A response code that is generated by the Payment Server to indicate the
     * status of the transaction.
     * A vpc_TxnResponseCode of “0” (zero) indicates that the transaction was
     * processed successfully and approved by the acquiring bank.
     * Any other value indicates that the transaction was declined (it went
     * through to the banking network) or the transaction failed (it never made
     * it to the banking network).
     * No matter what the condition, a meaningful transaction response should
     * always be communicated back to the cardholder to inform them of the
     * transaction outcome.
     * For a list of values, see Returned Response Codes on page 75.
     * Output Alphanumeric 1 0
     */
    const VPC_TXNRESPONSECODE = 'vpc_TxnResponseCode';

    const VPC_AVSRESPONSECODE = 'vpc_AVSResultCode';

    const VPC_ACQRESPONSECODE = 'vpc_AcqResponseCode';

    const VPC_MESSAGE         = 'vpc_Message';

    public static $errorCodeMap = [
        self::VPC_CSCRESULTCODE     => 'cscErrorCodeMap',
        self::VPC_AVSRESPONSECODE   => 'avsErrorCodeMap',
        self::VPC_TXNRESPONSECODE   => 'txnErrorCodeMap',
        self::VPC_MESSAGE           => 'vpcErrorCodeMap',
        self::VPC_ACQRESPONSECODE   => 'errorCodeMap',
    ];

    public static $errorDescriptionMap = [
        self::VPC_CSCRESULTCODE     => 'cscErrorDescriptionMap',
        self::VPC_AVSRESPONSECODE   => 'avsErrorDescriptionMap',
        self::VPC_TXNRESPONSECODE   => 'txnErrorDescriptionMap',
        self::VPC_MESSAGE           => 'vpcErrorDescriptionMap',
        self::VPC_ACQRESPONSECODE   => 'errorDescriptionMap',
    ];

    public static function getErrorCodeFields()
    {
        // This array tells the priority of the error code. Here VPC_MESSAGE is
        // the first priority because it provides most granular data among others
        return [
            self::VPC_MESSAGE,
            self::VPC_ACQRESPONSECODE,
            self::VPC_TXNRESPONSECODE,
            self::VPC_AVSRESPONSECODE,
            self::VPC_CSCRESULTCODE,
        ];
    }
}
