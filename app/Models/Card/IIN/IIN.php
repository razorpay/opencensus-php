    protected static function isValidCardForBank($bank, string $cardNumber): bool
    {
        if (in_array($bank, self::$emiBanks))
        {
            foreach (self::$emiIins[$bank] as $iin)
            {
                if (substr($cardNumber, 0, strlen($iin)) === $iin)
                {
                    return true;
                }
            }

            return false;
        }

        return true;
    }

    public static function getTransactingIinforRange($tokenizedNumber)
    {
        foreach(self::$tokenisedIinRange as $iinRange)
        {
            if (($tokenizedNumber === $iinRange[0]) or
                ($tokenizedNumber === $iinRange[1]) or
                (($tokenizedNumber >= $iinRange[1]) and
                 ($tokenizedNumber <= $iinRange[0])))
            {
                return $iinRange[2];
            }
        }
    }

    protected static function ignoreIinChecks(Entity $iin)
    {
        $issuer = $iin->getIssuer();
        $type = $iin->getType();

        return ((isset(self::$ignoreIinCheckForEmi[$issuer]) === true) AND
            (in_array($type, self::$ignoreIinCheckForEmi[$issuer])));
    }

    public static function validateEmiAvailableForCard(Entity $iin, array $cardNumberArray)
    {
        $cardNumber = $cardNumberArray['number'];

        // If we can not ignore IIN checks and if emi is not available for this card IIN
        if ((self::ignoreIinChecks($iin) === false) AND
            (self::isEmiAvailableForCard($iin, $cardNumber) === false))
        {
            throw new Exception\BadRequestException(
                ErrorCode::BAD_REQUEST_PAYMENT_EMI_NOT_AVAILABLE_ON_CARD);
        }
    }

    /**
     * This checks for the special case of Axis Bank which works on first 8 digits
     * of the card instea of the first 6.
     */
    public static function isEmiAvailableForCard(Entity $iin, string $cardNumber): bool
    {
        $emi = (($iin->isEmiAvailable()) and
                (self::isValidCardForBank($iin->getIssuer(), $cardNumber)));

        return $emi;
    }

    public static function isIinPrepaid($iin): bool
    {
        return in_array($iin, self::$prepaidIins);
    }
