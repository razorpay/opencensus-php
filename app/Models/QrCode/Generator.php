<?php

namespace RZP\Models\QrCode;

use RZP\Models\Base;
use RZP\Constants\Mode;
use RZP\Models\Merchant;
use RZP\Trace\TraceCode;
use RZP\Models\FileStore;
use BaconQrCode\Renderer;
use BaconQrCode\Writer;
use RZP\Models\VirtualAccount;
use RZP\Exception\LogicException;
use RZP\Models\FileStore\Utility;
use RZP\Services\Elfin\Service as Elfin;

class Generator extends Base\Core
{
    /**
     * @var Entity
     */
    protected $qrCode;

    /**
     * @var Merchant\Entity
     */
    protected $merchant;

    /**
     * Url shortener service
     * @var Elfin
     */
    protected $elfin;

    /**
     * Base qrcode url from which qr code link is generated.
     * @var string
     */
    protected $baseQrCodeUrl;

    // Qr code Extension
    const QR_CODE_EXTENSION = FileStore\Format::JPEG;

    const SHORT_MODE_LIVE = 'l';
    const SHORT_MODE_TEST = 't';

    public function __construct(Merchant\Entity $merchant)
    {
        parent::__construct();

        $this->merchant = $merchant;

        $this->elfin = $this->app['elfin'];

        $this->baseQrCodeUrl = $this->app['config']->get('app.url') .'/v1';
    }

    public function generate(array $input, VirtualAccount\Entity $virtualAccount): Entity
    {
        $this->createAndSetQrCode($input);

        $qrCode = $this->qrCode;

        $qrCode->merchant()->associate($this->merchant);

        $qrCode->source()->associate($virtualAccount);

        //
        // The only case when reference will not be equal to ID is
        // when the QR code is generated by the client/merchant system
        // and not RZP system. If the QR code is generated by the
        // merchant, we don't care about generating the QR string and
        // hence the image  and hence the URL, because the QR code
        // has already been generated by the merchant.
        // Note: The reference will not be equal to ID here because
        //       the merchant would have used their own reference
        //       while generating the QR code.
        //
        // This happens when the terminal's expected attribute is
        // set to true, in which case, whatever reference we get in
        // the notification, we treat the notification as expected.
        // If the terminal's expected attribute is set to false, we
        // treat the notification as unexpected and it would never
        // reach this flow because the unexpected notifications are
        // created against one shared QR code.
        //
        if ($qrCode->isGeneratedByMerchant() === false)
        {
            $qrCode->generateQrString();

            $this->setShortUrl();
        }

        $this->repo->transaction(function() use ($qrCode)
        {
            $this->repo->saveOrFail($qrCode);

            $this->generateQrCodeFile();
        });

        return $this->qrCode;
    }

    protected function createAndSetQrCode(array $input)
    {
        $this->qrCode = (new Entity)->build($input);
    }

    protected function setShortUrl()
    {
        $longUrl = $this->getQrCodeLink();

        $shortenedUrl = $this->elfin->shorten($longUrl);

        $this->trace->info(
            TraceCode::QR_CODE_URL,
            [
                'qr_code_id'     => $this->qrCode->getId(),
                'short_url'      => $shortenedUrl,
                'long_url'       => $longUrl,
            ]);

        $this->qrCode->setShortUrl($shortenedUrl);
    }

    protected function getQrCodeLink(): string
    {
        $qrCodePublicId = $this->qrCode->getPublicId();

        if ($this->mode === Mode::LIVE)
        {
            $shortMode = self::SHORT_MODE_LIVE;
        }
        else
        {
            $shortMode = self::SHORT_MODE_TEST;
        }

        $qrCodeLink = $this->baseQrCodeUrl . '/' . $shortMode . '/qrcode/' . $qrCodePublicId;

        return $qrCodeLink;
    }

    protected function generateQrCodeFile()
    {
        //
        // There are cases when we don't generate a QR string for QR codes.
        // Refer to the function `generate` for more information around this.
        //
        if (empty($this->qrCode->getQrString()) === true)
        {
            return;
        }

        $localFilePath = $this->generateQrCodeImage();

        $ext = self::QR_CODE_EXTENSION;

        (new FileStore\Creator)
                    ->localFilePath($localFilePath)
                    ->mime(FileStore\Format::VALID_EXTENSION_MIME_MAP[$ext][0])
                    ->name($this->qrCode->getQrCodeFileName())
                    ->extension($ext)
                    ->entity($this->qrCode)
                    ->type(FileStore\Type::QR_CODE_IMAGE)
                    ->save();
    }

    protected function generateQrCodeImage()
    {
        $renderer = new Renderer\Image\Png;

        $renderer->setMargin(0);

        $renderer->setHeight(Constants::QR_CODE_HEIGHT);

        $renderer->setWidth(Constants::QR_CODE_WIDTH);

        $writer = new Writer($renderer);

        $localFilePath = $this->getLocalSaveDir() . '/' . $this->qrCode->getId() . '.' . self::QR_CODE_EXTENSION;

        $qrCodeString = $writer->writeString($this->qrCode->getQrString());

        $logoImage = imagecreatefromjpeg(public_path().'/img/qr.jpg');

        $qrCodeImage = imagecreatefromstring($qrCodeString);

        imagecopymerge($logoImage, $qrCodeImage, 30, 200, 0, 0,
                Constants::QR_CODE_WIDTH, Constants::QR_CODE_HEIGHT, 100);

        imagejpeg($logoImage, $localFilePath);

        imagedestroy($logoImage);

        imagedestroy($qrCodeImage);

        return $localFilePath;
    }

    protected function getLocalSaveDir(): string
    {
        $dirPath = storage_path('files/qrcodes');

        if (file_exists($dirPath) === false)
        {
            (new Utility)->callFileOperation('mkdir', [$dirPath, 0777, true]);
        }

        return $dirPath;
    }
}
