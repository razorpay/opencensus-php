export const BUYER_ADDRESS_VALIDATION_SCHEMA = object().shape({
  [FIELDS_MAPPING.LINE1]: string().max(255).required('Buyer address is required'),
  [FIELDS_MAPPING.CITY]: string().min(2).max(32).required('Buyer city is required'),
  [FIELDS_MAPPING.NAME]: string().min(2).max(64).required('Name of business is required'),
  [FIELDS_MAPPING.POSTAL_CODE]: string()
    .min(2)
    .max(10)
    .matches(/^(?=.*[0-9])[A-Za-z0-9\s]*$/, 'Please enter a valid postal code')
    .required('Buyer postal code is required'),
  [FIELDS_MAPPING.STATE]: string().min(2).max(32).required('Buyer state is required'),
  [FIELDS_MAPPING.COUNTRY]: string().min(2).max(32).required('Buyer country is required'),
});

