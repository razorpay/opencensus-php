import React from 'react';
import {
  Modal,
  ModalHeader,
  ModalBody,
  ModalFooter,
  Box,
  Text,
  Button,
  Alert,
} from '@razorpay/blade/components';

import { trackRequestFirsButtonClick } from 'merchant/views/AccountAndSettings/InternationalSettings/analytics';
import {
  PopupTitle,
  PopupType,
} from 'merchant/views/AccountAndSettings/InternationalSettings/constants';
import useFirsContext from 'merchant/views/AccountAndSettings/InternationalSettings/hooks/useFirsContext';
import { ActionPopupPropsT } from 'merchant/views/AccountAndSettings/InternationalSettings/typings';
import { useSplitzService } from 'common/splitz';
import { isExperimentEnabled } from 'common/splitz/utils';

const getModalBody = (popupType, month, year, customMessage) => {
  switch (popupType) {
    case PopupType.SUCCESS_MODAL:
      return (
        <Box display="flex" flexDirection="column" alignItems="center">
          <Box marginBottom="spacing.7">
            <img src="https://cdn.razorpay.com/static/assets/international/success-check.svg" />
          </Box>
          <Text size="large" marginBottom="spacing.5" textAlign="center" weight="semibold">
            Razorpay statement request has been sent!
          </Text>
          <Text size="small" textAlign="center" color="surface.text.gray.muted">
            It may take up to 2 hours for the statement to get generated. You would be able to
            conveniently download it from the dashboard once it's generated.
          </Text>
        </Box>
      );
    default:
      return (
        <Box display="flex" flexDirection="column" alignItems="center">
          <Text size="medium" marginBottom="spacing.5" textAlign="center">
            FIRS for {month} {year} has not been generated by your bank(s) yet.
          </Text>
          <Text size="small" textAlign="center" color="surface.text.gray.muted">
            Bank FIRS is/are usually available for download after the 15th of the next month. You
            can also request for statement generated on the Razorpay letterhead.
          </Text>
          {customMessage && (
            <Alert
              marginTop="spacing.5"
              color="notice"
              isDismissible={false}
              isFullWidth
              description={customMessage}
            />
          )}
        </Box>
      );
  }
};

const getButtonText = (popupType) => {
  switch (popupType) {
    case PopupType.SUCCESS_MODAL:
      return 'Back to download FIRS';
    default:
      return 'Request for Razorpay statement';
  }
};

const ActionPopup = ({ popupType }: ActionPopupPropsT) => {
  const { popupData, setPopupData } = useFirsContext();
  const {
    abExperiments: { firs_messaging },
  } = useSplitzService();

  const isFirsExpEnabled = isExperimentEnabled(firs_messaging);
  const customMessage = isFirsExpEnabled ? firs_messaging?.variables?.message : null;
  const { isOpen, type, month, year } = popupData;

  const isPopupOpen = isOpen && type === popupType;

  const onDismiss = () => {
    setPopupData((prev) => ({
      ...prev,
      isOpen: false,
    }));
  };

  const onClick = () => {
    const isSuccessModal = popupType === PopupType.SUCCESS_MODAL;
    const redirectTo = isSuccessModal ? PopupType.DOWNLOAD_FIRS : PopupType.INTERNAL_FIRS;
    if (!isSuccessModal) trackRequestFirsButtonClick(month, year);
    setPopupData((prev) => ({
      ...prev,
      type: redirectTo,
    }));
  };

  return (
    <Modal isOpen={isPopupOpen} onDismiss={onDismiss} size="small" zIndex={10000}>
      <ModalHeader title={PopupTitle[popupType]} />
      <ModalBody>{getModalBody(popupType, month, year, customMessage)}</ModalBody>
      <ModalFooter>
        <Box>
          <Button variant="primary" isFullWidth onClick={onClick}>
            {getButtonText(popupType)}
          </Button>
        </Box>
      </ModalFooter>
    </Modal>
  );
};

export default ActionPopup;
