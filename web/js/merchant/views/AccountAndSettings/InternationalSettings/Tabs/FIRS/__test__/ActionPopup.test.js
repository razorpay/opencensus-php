import { dateObject } from 'merchant/views/AccountAndSettings/InternationalSettings/Tabs/FIRS/__test__/fixtures';
import { mockContextData } from 'merchant/views/AccountAndSettings/InternationalSettings/Tabs/FIRS/__test__/fixtures/mocks';
import ActionPopup from 'merchant/views/AccountAndSettings/InternationalSettings/Tabs/FIRS/components/RequestModals/ActionPopup';
import {
  PopupTitle,
  PopupType,
} from 'merchant/views/AccountAndSettings/InternationalSettings/constants';
import { render, screen, userEvent, waitFor } from 'test-utils';
import { useSplitzService } from 'common/splitz';

jest.mock('common/splitz', () => ({
  useSplitzService: jest.fn(() => ({
    abExperiments: {
      firs_messaging: {
        variables: {
          result: 'off',
          message: 'dummy message',
        },
      },
    },
  })),
}));

const renderApp = (props = {}) => {
  render(<ActionPopup {...props} />);
};

describe('Tests for ActionPopup component', () => {
  const { month, year } = dateObject;
  const popupData = {
    isOpen: true,
    type: PopupType.NO_FIRS,
    month,
    year,
  };
  const callBack = jest.fn();
  const setPopupData = jest.fn((anonymousFunc) => callBack(anonymousFunc?.()));

  beforeAll(() => jest.clearAllMocks());

  test('Correct Modal info should be visible PopupType is NO_FIRS', () => {
    const popupType = PopupType.NO_FIRS;
    mockContextData({ popupData, setPopupData });
    renderApp({ popupType });

    //Popup data for NO_FIRS
    expect(screen.getByText(PopupTitle[popupType])).toBeInTheDocument();
    expect(screen.getByText('Request for Razorpay statement')).toBeInTheDocument();
    expect(
      screen.getByText(`FIRS for ${month} ${year} has not been generated by your bank(s) yet.`),
    ).toBeInTheDocument();
  });

  test('Correct Modal info should be visible PopupType is SUCCESS_MODAL', () => {
    const popupType = PopupType.SUCCESS_MODAL;
    mockContextData({ popupData: { ...popupData, type: popupType }, setPopupData });
    renderApp({ popupType });

    //Popup data for NO_FIRS
    expect(screen.getByText(PopupTitle[popupType])).toBeInTheDocument();
    expect(screen.getByText('Back to download FIRS')).toBeInTheDocument();
    expect(screen.getByText('Razorpay statement request has been sent!')).toBeInTheDocument();
  });

  test('Popup should default back to NO_FIRS modal if popup type is wrong', () => {
    const popupType = 'DUMMY_TYPE';
    mockContextData({ popupData: { ...popupData, type: popupType }, setPopupData });
    renderApp({ popupType });

    expect(screen.getByText('Request for Razorpay statement')).toBeInTheDocument();
    expect(
      screen.getByText(`FIRS for ${month} ${year} has not been generated by your bank(s) yet.`),
    ).toBeInTheDocument();
  });

  test('Button click should redirect to correct popup if popupType in SUCCESS_MODAL', async () => {
    const popupType = PopupType.SUCCESS_MODAL;
    mockContextData({ popupData: { ...popupData, type: popupType }, setPopupData });
    renderApp({ popupType });

    await userEvent.click(screen.getByText('Back to download FIRS'));
    await waitFor(() => {
      expect(callBack).toHaveBeenCalledWith(
        expect.objectContaining({
          type: PopupType.DOWNLOAD_FIRS,
        }),
      );
    });
  });

  test('Button click should redirect to correct popup if popupType in NO_FIRS', async () => {
    const popupType = PopupType.NO_FIRS;
    mockContextData({ popupData: { ...popupData, type: popupType }, setPopupData });
    renderApp({ popupType });

    await userEvent.click(screen.getByText('Request for Razorpay statement'));
    await waitFor(() => {
      expect(callBack).toHaveBeenCalledWith(
        expect.objectContaining({
          type: PopupType.INTERNAL_FIRS,
        }),
      );
    });
  });

  test('Close icon should be visible and functional', async () => {
    const popupType = PopupType.NO_FIRS;
    mockContextData({ popupData, setPopupData });
    renderApp({ popupType });

    //close icon should be visible
    expect(screen.getByLabelText('Close')).toBeInTheDocument();
    await userEvent.click(screen.getByLabelText('Close'));
    await waitFor(() => expect(setPopupData).toHaveBeenCalled());
  });

  test('Should not show notice if experiment is enabled', () => {
    const popupType = PopupType.NO_FIRS;
    mockContextData({ popupData, setPopupData });
    renderApp({ popupType });

    expect(screen.queryByText('dummy message')).not.toBeInTheDocument();
  });

  test('Should show notice if experiment is enabled', () => {
    const popupType = PopupType.NO_FIRS;
    mockContextData({ popupData, setPopupData });

    // eslint-disable-next-line
    // @ts-ignore
    useSplitzService.mockImplementation(() => ({
      abExperiments: {
        firs_messaging: {
          variables: {
            result: 'on',
            message: 'dummy message',
          },
        },
      },
    }));

    renderApp({ popupType });

    expect(screen.getByText('dummy message')).toBeInTheDocument();
  });
});
