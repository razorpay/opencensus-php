import React from 'react';
import { render, screen } from '@apps/payroll-app/src/services/test/jest-utils';
import { App } from '@apps/payroll-app/src/App';
import { APP_CONSTANTS } from '@apps/payroll-app/src/constants';
import { toTitleCase } from '@libs/shared-utils';

jest.mock('@apps/payroll-app/src/constants', () => ({
  APP_CONSTANTS: {
    APP_NAME: 'test-app',
  },
}));

describe('App', () => {
  it('renders the heading with the formatted app name', () => {
    render(<App />);

    const expectedTitle = toTitleCase(APP_CONSTANTS.APP_NAME.split('-').join(' '));
    expect(screen.getByRole('heading')).toHaveTextContent(`Welcome ${expectedTitle}!`);
  });

  it('renders the caption text', () => {
    render(<App />);
    expect(
      screen.getByText('This app is generated by dashboard-cli. Happy coding!'),
    ).toBeInTheDocument();
  });
});
